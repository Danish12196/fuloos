// Copies the generic rule tables from the Ledger project (ledger-uae-banks/site/try/ledger-rules.js) into
// src/ledger/rules.generated.ts.
//
//   node --experimental-strip-types scripts/ledger/import-rules.ts ../ledger-uae-banks/site/try/ledger-rules.js
//
// Only public, non-personal tables are copied: bank SMS templates, public brand patterns, category keywords and
// descriptions. OVERRIDES is deliberately dropped: it lists specific merchants taken from the contributors' own
// SMS (local shops, clinics, home areas) and must never be committed to this repository.
import { readFileSync, writeFileSync } from "node:fs";
import { runInNewContext } from "node:vm";

const KEEP = [
  "AED_PER_UNIT",
  "COMMON_RULES",
  "BANK_RULES",
  "BALANCE_RX",
  "UAE_CITIES",
  "BRANDS",
  "FUEL_BRANDS",
  "FOOD_AT_STATION",
  "TRANSFER_MERCHANTS",
  "BNPL_MERCHANTS",
  "CATEGORIES",
  "BRAND",
  "AMBIGUOUS",
  "KEYWORDS",
  "CITY",
  "RULE_CONF",
] as const;
const DROPPED = new Set(["OVERRIDES", "source"]);

const source = process.argv[2];
if (!source) {
  console.error("Usage: import-rules.ts <path to ledger-rules.js>");
  process.exit(1);
}
const sandbox: { globalThis?: unknown; LedgerRules?: Record<string, unknown> } =
  {};
sandbox.globalThis = sandbox;
runInNewContext(readFileSync(source, "utf8"), sandbox);
const rules = sandbox.LedgerRules;
if (!rules) throw new Error("ledger-rules.js did not define LedgerRules.");
const unknown = Object.keys(rules).filter(
  (k) => !DROPPED.has(k) && !(KEEP as readonly string[]).includes(k),
);
if (unknown.length)
  throw new Error(
    `New table(s) ${unknown.join(", ")}: review them for personal data, then add to KEEP or DROPPED.`,
  );
const picked = Object.fromEntries(KEEP.map((k) => [k, rules[k]]));
const out = `/* Generated by scripts/ledger/import-rules.ts from the Ledger project's ledger-rules.js. Do not edit by hand.
   Generic tables only: personal merchant overrides are intentionally excluded. */
export const LEDGER_RULES = ${JSON.stringify(picked, null, 1)} as const;
`;
writeFileSync(
  new URL("../../src/ledger/rules.generated.ts", import.meta.url),
  out,
);
console.log(`Wrote ${KEEP.length} tables; dropped ${[...DROPPED].join(", ")}.`);
